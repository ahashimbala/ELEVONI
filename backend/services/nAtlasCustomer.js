import Product from "../models/Product.js";
import fishModel from "../models/fishModel.js";
import { CATALOGUE_QUERY } from "./catalogue.js";
import vendorProfileModel from "../models/vendorProfileModel.js";
import { PRODUCT_CATEGORIES, SUBCATEGORIES_BY_CATEGORY } from "../../shared/categoryConstants.mjs";
import { createTimer } from "../utils/timingLogger.mjs";
import { buildListingFilter, isCatalogueOverviewRequest, normalizeCustomerCriteria, normalizeLgaName, normalizeStateName, rankCustomerListings } from "./nAtlasCustomerMatching.js";
import { createOpenAIResponse, ELEVONI_LANGUAGES, openAIError } from "./openaiApi.js";

const LANGUAGES = Object.freeze({
  "en-NG": "Nigerian English", "pcm-NG": "Nigerian Pidgin", "ha-NG": "Hausa", "ig-NG": "Igbo", "yo-NG": "Yoruba",
});
const MAX_MESSAGE_LENGTH = 1200;
const MAX_HISTORY = 8;
const clean = (value, max = 160) => typeof value === "string" ? value.trim().slice(0, max) : "";

const customerCriteriaSchema = {
  name: "elevoni_customer_search_criteria",
  schema: {
    type: "object", additionalProperties: false,
    properties: {
      intent: { type: "string", enum: ["search", "navigate", "overview", "general"] },
      category: { type: "string" },
      subcategory: { type: "string" },
      keywords: { type: "array", items: { type: "string" } },
      state: { type: "string" },
      lga: { type: "string" },
      minPrice: { anyOf: [{ type: "number" }, { type: "null" }] },
      maxPrice: { anyOf: [{ type: "number" }, { type: "null" }] },
      quantity: { anyOf: [{ type: "number" }, { type: "null" }] },
      unit: { type: "string" },
      destination: { type: "string", enum: ["marketplace", "livestock", "food-crops", "aquaculture-fishery", "smoked-catfish", ""] },
    },
    required: ["intent", "category", "subcategory", "keywords", "state", "lga", "minPrice", "maxPrice", "quantity", "unit", "destination"],
  },
};

async function localizeCustomerReply({ language, fallback, abortSignal, timer }) {
  if (language === "en-NG") return fallback;
  const languageName = LANGUAGES[language] || LANGUAGES["en-NG"];
  try {
    const result = await createOpenAIResponse({
      instructions: `You are Elevoni Assistant. Rewrite the supplied short customer-service message in clear, natural ${languageName} only. The selected language is ${language}. Do not answer the user, switch to English, mix languages, or add information. Preserve meaning, product names, stock status, prices, locations and numbers exactly. For Nigerian Pidgin, use natural Nigerian Pidgin, not formal English. Return only the rewritten message.`,
      input: [{ role: "user", content: fallback }],
      maxOutputTokens: 180,
      abortSignal,
    });
    const translated = clean(result.text, 700).replace(/^['"“”]+|['"“”]+$/g, "");
    if (!translated) throw openAIError(`Could not prepare the response in ${languageName}. Please try again.`, 502, "OPENAI_CUSTOMER_LANGUAGE_FAILED");
    return translated;
  } catch (error) {
    timer?.log("customer-localization-failed", { language, code: error?.code || null });
    throw error;
  }
}

async function understandRequest({ message, language, history, abortSignal, timer }) {
  const languageName = LANGUAGES[language] || LANGUAGES["en-NG"];
  const instructions = `You are Elevoni Assistant, the customer-facing agricultural commerce assistant. Understand the customer's request and extract search/navigation criteria. Classify broad questions such as 'What products are available on Elevoni?', 'What does Elevoni sell?' or 'What can I buy here?' as intent=overview so the server can show both Elevoni Direct products and approved Marketplace listings. The selected response language is ${languageName} (${language}); all user-facing text generated by the application must use that language. For Nigerian Pidgin, use natural Nigerian Pidgin. Preserve product names, locations, quantities and prices exactly. minPrice and maxPrice are per-unit price filters only when the user explicitly gives a per-unit budget; leave them null for an unclear total budget. Return structured criteria only. Do not invent missing details, listings, prices, stock, farmers, delivery coverage or business policies. Only classify; the server will search visible Elevoni Direct products and real approved Marketplace listings. If the customer asks to navigate, set intent=navigate and destination only when clear. If unsure, use general. Categories: ${PRODUCT_CATEGORIES.join(" | ")}. Subcategories: ${JSON.stringify(SUBCATEGORIES_BY_CATEGORY)}. Conversation history is context, not a source of listing facts.`;
  const input = (Array.isArray(history) ? history : []).slice(-MAX_HISTORY).map((item) => ({
    role: item?.role === "assistant" ? "assistant" : "user", content: clean(item?.text, 700),
  })).filter((item) => item.content);
  input.push({ role: "user", content: clean(message, MAX_MESSAGE_LENGTH) });
  timer?.log("customer-openai-request-start");
  const result = await createOpenAIResponse({
    instructions,
    input,
    schema: customerCriteriaSchema,
    maxOutputTokens: 400,
    abortSignal,
  });
  timer?.log("customer-openai-request-end", { model: result.model });
  return normalizeCustomerCriteria(result.parsed || {}, message);
}

function serialiseListing({ product, stockMatch }, criteria, sourceType = "marketplace") {
  const vendor = product.vendorId && typeof product.vendorId === "object" ? product.vendorId : {};
  const isDirect = sourceType === "direct";
  const state = vendor.state || vendor.farmAddress?.state || product.originLocation?.state || "";
  const lga = vendor.lga || vendor.farmAddress?.lga || product.originLocation?.lga || "";
  return {
    id: String(product._id), name: clean(product.name, 120), description: clean(product.description, 260),
    category: clean(product.category, 80), subcategory: clean(product.subcategory, 80),
    price: Number(product.price), unit: clean(product.unitOfMeasure, 24),
    image: Array.isArray(product.images) ? product.images[0] || "" : "",
    vendorName: isDirect ? "Elevoni Farms" : clean(vendor.businessName, 120),
    sourceType,
    sourceLabel: isDirect ? "Elevoni Direct" : "Marketplace listing",
    state, lga, stockMatch,
    matchReasons: [criteria.subcategory ? "Product type" : criteria.category ? "Product category" : "Product name", criteria.state && normalizeStateName(state) === normalizeStateName(criteria.state) ? "State" : "", criteria.lga && normalizeLgaName(lga) === normalizeLgaName(criteria.lga) ? "LGA" : "", stockMatch === "sufficient" ? "Recorded stock quantity" : ""].filter(Boolean),
    availability: product.availability || (product.isAvailable ? "Listed as available" : "Not available"),
  };
}

function serialiseDirectFish(fish, criteria) {
  const firstTierPrice = Array.isArray(fish.pricingTiers) && fish.pricingTiers.length
    ? Number(fish.pricingTiers[0].unitPrice)
    : Number(fish.price);
  return {
    id: String(fish._id),
    name: clean(fish.name, 120),
    description: clean(fish.description, 260),
    category: clean(fish.category || "Smoked Catfish", 80),
    subcategory: "Smoked Catfish",
    price: firstTierPrice,
    pricePrefix: fish.pricingMode === "tiered" ? "From" : "",
    unit: "kg",
    image: clean(fish.image, 500),
    vendorName: "Elevoni Farms",
    sourceType: "direct",
    sourceLabel: "Elevoni Direct",
    state: "",
    lga: "",
    stockMatch: "not_confirmed",
    matchReasons: ["Elevoni Direct catalogue"],
    availability: "Check current availability with Elevoni",
    houseProduct: true,
  };
}

function directFishMatches(fish, criteria) {
  const searchable = `${fish.name || ""} ${fish.description || ""} ${fish.category || ""}`.toLowerCase();
  if (criteria.keywords?.length && !criteria.keywords.some((word) => searchable.includes(word.toLowerCase()))) return false;
  const price = Array.isArray(fish.pricingTiers) && fish.pricingTiers.length
    ? Number(fish.pricingTiers[0].unitPrice)
    : Number(fish.price);
  if (criteria.unit && criteria.unit !== "kg") return false;
  if (criteria.minPrice !== null && price < criteria.minPrice) return false;
  if (criteria.maxPrice !== null && price > criteria.maxPrice) return false;
  return true;
}

function routeForDestination(destination) {
  return ({ marketplace: "/marketplace", livestock: "/category/livestock", "food-crops": "/category/food-crops", "aquaculture-fishery": "/category/aquaculture-fishery", "smoked-catfish": "/#fish-display" })[destination] || "";
}

export async function answerCustomerElevoniAssistant({ message, language = "en-NG", history = [], abortSignal, requestId }) {
  const timer = createTimer(requestId);
  timer.log("customer-request-start");
  const cleanMessage = clean(message, MAX_MESSAGE_LENGTH);
  if (!cleanMessage) {
    const error = new Error("Tell Elevoni Assistant what you are looking for."); error.status = 400; error.code = "ELEVONI_ASSISTANT_MESSAGE_EMPTY"; throw error;
  }
  if (!ELEVONI_LANGUAGES[language]) {
    const error = new Error("Choose one of Elevoni Assistant's supported languages."); error.status = 400; error.code = "ELEVONI_ASSISTANT_LANGUAGE_UNSUPPORTED"; throw error;
  }
  if (abortSignal?.aborted) {
    const error = new Error("Request cancelled."); error.status = 499; error.code = "NATLAS_CLIENT_ABORTED"; throw error;
  }

  const criteria = await understandRequest({ message: cleanMessage, language, history, abortSignal, timer });
  const isOverview = criteria.intent === "overview" || isCatalogueOverviewRequest(cleanMessage);

  if (criteria.intent === "navigate" && criteria.destination) {
    return {
      reply: await localizeCustomerReply({ language, fallback: "I can take you there. Tap the button below to open that part of Elevoni.", abortSignal, timer }),
      navigation: { label: await localizeCustomerReply({ language, fallback: `Open ${criteria.destination === "food-crops" ? "Food Crops" : criteria.destination === "aquaculture-fishery" ? "Aquaculture & Fishery" : criteria.destination === "smoked-catfish" ? "Smoked Catfish" : criteria.destination[0].toUpperCase() + criteria.destination.slice(1)}`, abortSignal, timer }), path: routeForDestination(criteria.destination) },
      listings: [],
    };
  }

  if (/\b(near me|nearby|closest|close to me)\b/i.test(cleanMessage) && !criteria.state && !criteria.lga) {
    return {
      reply: await localizeCustomerReply({ language, fallback: "Tell me your state or town so I can look for nearby listings. I do not assume your location.", abortSignal, timer }),
      navigation: { label: await localizeCustomerReply({ language, fallback: "Browse the marketplace", abortSignal, timer }), path: "/marketplace" }, listings: [],
    };
  }

  if (!isOverview && !criteria.category && !criteria.subcategory && !criteria.keywords.length) {
    return {
      reply: await localizeCustomerReply({ language, fallback: "I can help you find livestock, food crops, aquaculture and fishery products. Tell me the product, quantity and the state or town you prefer.", abortSignal, timer }),
      navigation: { label: await localizeCustomerReply({ language, fallback: "Browse the marketplace", abortSignal, timer }), path: "/marketplace" }, listings: [],
    };
  }

  const approvedProfiles = await vendorProfileModel.find({ status: "approved" }).select("_id state lga farmAddress").lean();
  const locationProfiles = approvedProfiles.filter((profile) => {
    const state = profile.state || profile.farmAddress?.state || "";
    const lga = profile.lga || profile.farmAddress?.lga || "";
    return (!criteria.state || normalizeStateName(state) === normalizeStateName(criteria.state))
      && (!criteria.lga || normalizeLgaName(lga) === normalizeLgaName(criteria.lga));
  });
  const approvedVendorIds = (criteria.state || criteria.lga ? locationProfiles : approvedProfiles).map((profile) => profile._id);

  const shouldSearchProducts = isOverview || Boolean(criteria.category || criteria.subcategory || criteria.keywords.length);
  let marketplaceListings = [];
  let directListings = [];

  if (shouldSearchProducts && approvedVendorIds.length) {
    const marketplaceFilter = buildListingFilter(criteria, approvedVendorIds);
    const foundMarketplace = await Product.find(marketplaceFilter)
      .select("name description category subcategory price unitOfMeasure images vendorId originLocation stockQuantity availability isAvailable updatedAt")
      .populate("vendorId", "businessName state lga farmAddress status")
      .sort({ updatedAt: -1 }).limit(isOverview ? 40 : 40).lean();
    marketplaceListings = rankCustomerListings(foundMarketplace, criteria, isOverview ? 20 : 8)
      .map((item) => serialiseListing(item, criteria, "marketplace"));
  }

  // Product documents with no vendor owner are Elevoni-owned Direct products.
  if (shouldSearchProducts) {
    const directProductFilter = buildListingFilter(criteria, []);
    directProductFilter.vendorId = null;
    const foundDirectProducts = await Product.find(directProductFilter)
      .select("name description category subcategory price unitOfMeasure images vendorId originLocation stockQuantity availability isAvailable updatedAt")
      .sort({ updatedAt: -1 }).limit(40).lean();

    const matchingDirectProducts = foundDirectProducts.filter((product) => {
      const state = product.originLocation?.state || "";
      const lga = product.originLocation?.lga || "";
      return (!criteria.state || normalizeStateName(state) === normalizeStateName(criteria.state))
        && (!criteria.lga || normalizeLgaName(lga) === normalizeLgaName(criteria.lga));
    });

    directListings.push(...rankCustomerListings(matchingDirectProducts, criteria, isOverview ? 20 : 8)
      .map((item) => serialiseListing(item, criteria, "direct")));
  }

  const shouldSearchDirectFish = isOverview
    || criteria.keywords.some((word) => /fish|catfish|smoked/i.test(word))
    || /smoked catfish|smoked fish|catfish/i.test(cleanMessage);

  // The legacy fish catalogue is also an Elevoni Direct source. Only records
  // without a vendor owner are treated as Elevoni-owned products.
  if (shouldSearchDirectFish && !criteria.state && !criteria.lga) {
    const directFish = await fishModel.find({ ...CATALOGUE_QUERY, vendorId: null })
      .select("name description price image category pricingMode pricingTiers vendorId")
      .sort({ _id: -1 }).limit(isOverview ? 30 : 20).lean();

    directListings.push(...directFish
      .filter((fish) => directFishMatches(fish, criteria))
      .map((fish) => serialiseDirectFish(fish, criteria)));
  }

  if (isOverview) {
    const listings = [...directListings, ...marketplaceListings];
    const directNames = directListings.slice(0, 5).map((item) => item.name).filter(Boolean);
    const marketplaceNames = marketplaceListings.slice(0, 5).map((item) => item.name).filter(Boolean);
    const directSummary = directListings.length
      ? `Elevoni Direct: ${directListings.length} listed product(s)${directNames.length ? ` including ${directNames.join(", ")}` : ""}.`
      : "Elevoni Direct: no visible products were found in the current catalogue.";
    const marketplaceSummary = marketplaceListings.length
      ? `Marketplace: ${marketplaceListings.length} approved available vendor listing(s)${marketplaceNames.length ? ` including ${marketplaceNames.join(", ")}` : ""}.`
      : "Marketplace: no approved available vendor listings were found for this search.";
    const fallback = `Elevoni has two product sources. ${directSummary} ${marketplaceSummary} Direct products are sold by Elevoni; Marketplace products are listed by independent vendors. Listings do not guarantee live stock, so confirm availability, final price and delivery before paying.`;
    const reply = await localizeCustomerReply({ language, fallback, abortSignal, timer });
    timer.log("customer-catalogue-overview-end", {
      directProducts: directListings.length,
      marketplaceListings: marketplaceListings.length,
    });
    return {
      reply,
      navigation: { label: await localizeCustomerReply({ language, fallback: "Browse all products", abortSignal, timer }), path: "/marketplace" },
      listings,
      catalogue: {
        directCount: directListings.length,
        marketplaceCount: marketplaceListings.length,
      },
    };
  }

  const listings = [...directListings, ...marketplaceListings];

  if (!listings.length) {
    return {
      reply: await localizeCustomerReply({ language, fallback: criteria.state || criteria.lga ? "I could not find a visible Elevoni Direct product or approved Marketplace listing matching those details in that location. Try another state or town, or browse all marketplace listings." : "I couldn't find a visible Elevoni Direct product or approved Marketplace listing matching those details right now. You can broaden the search by changing the product, location or budget. No supplier or stock has been assumed.", abortSignal, timer }),
      navigation: { label: await localizeCustomerReply({ language, fallback: "Browse all marketplace listings", abortSignal, timer }), path: "/marketplace" }, listings: [],
    };
  }

  const locationText = [criteria.lga, criteria.state].filter(Boolean).join(", ");
  const reply = await localizeCustomerReply({
    language,
    fallback: `I found matching products${locationText ? ` for ${locationText}` : ""}. Elevoni Direct products are sold by Elevoni; Marketplace listings are offered by independent vendors. These are listings, not confirmed orders. Please confirm current stock, final price and delivery before paying.`,
    abortSignal,
    timer,
  });
  timer.log("customer-request-end", { matchedListings: listings.length, intent: criteria.intent });
  return {
    reply,
    navigation: { label: await localizeCustomerReply({ language, fallback: "See all marketplace listings", abortSignal, timer }), path: "/marketplace" },
    listings,
    criteria: { category: criteria.category, subcategory: criteria.subcategory, state: criteria.state, lga: criteria.lga, quantity: criteria.quantity, unit: criteria.unit },
  };
}
