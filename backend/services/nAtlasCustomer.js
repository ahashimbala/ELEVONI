import Product from "../models/Product.js";
import fishModel from "../models/fishModel.js";
import { CATALOGUE_QUERY } from "./catalogue.js";
import vendorProfileModel from "../models/vendorProfileModel.js";
import { PRODUCT_CATEGORIES, SUBCATEGORIES_BY_CATEGORY } from "../../shared/categoryConstants.mjs";
import { createTimer } from "../utils/timingLogger.mjs";
import { buildListingFilter, normalizeCustomerCriteria, normalizeLgaName, normalizeStateName, rankCustomerListings } from "./nAtlasCustomerMatching.js";
import { createOpenAIResponse, ELEVONI_LANGUAGES, openAIError } from "./openaiApi.js";
import { inferCustomerCartRequest, matchDirectCatalogueProduct, resolveCartQuantity } from "./nAtlasCustomerCart.js";

const LANGUAGES = Object.freeze({
  "en-NG": "Nigerian English", "pcm-NG": "Nigerian Pidgin", "ha-NG": "Hausa", "ig-NG": "Igbo", "yo-NG": "Yoruba",
});
const MAX_MESSAGE_LENGTH = 1200;
const MAX_HISTORY = 8;
const clean = (value, max = 160) => typeof value === "string" ? value.trim().slice(0, max) : "";

const customerCriteriaSchema = {
  name: "elevoni_customer_search_criteria",
  schema: {
    type: "object", additionalProperties: false,
    properties: {
      intent: { type: "string", enum: ["search", "navigate", "general", "cart", "demand"] },
      action: { type: "string", enum: ["none", "set_quantity", "add_quantity", "subtract_quantity", "remove_item", "clear_cart", "view_cart", "checkout"] },
      productName: { type: "string" },
      category: { type: "string" },
      subcategory: { type: "string" },
      keywords: { type: "array", items: { type: "string" } },
      state: { type: "string" },
      lga: { type: "string" },
      minPrice: { anyOf: [{ type: "number" }, { type: "null" }] },
      maxPrice: { anyOf: [{ type: "number" }, { type: "null" }] },
      quantity: { anyOf: [{ type: "number" }, { type: "null" }] },
      unit: { type: "string" },
      destination: { type: "string", enum: ["marketplace", "livestock", "food-crops", "aquaculture-fishery", "smoked-catfish", ""] },
    },
    required: ["intent", "action", "productName", "category", "subcategory", "keywords", "state", "lga", "minPrice", "maxPrice", "quantity", "unit", "destination"],
  },
};

async function localizeCustomerReply({ language, fallback, abortSignal, timer }) {
  if (language === "en-NG") return fallback;
  const languageName = LANGUAGES[language] || LANGUAGES["en-NG"];
  try {
    const result = await createOpenAIResponse({
      instructions: `You are Elevoni Assistant. Rewrite the supplied short customer-service message in clear, natural ${languageName} only. The selected language is ${language}. Do not answer the user, switch to English, mix languages, or add information. Preserve meaning, product names, stock status, prices, locations and numbers exactly. For Nigerian Pidgin, use natural Nigerian Pidgin, not formal English. Return only the rewritten message.`,
      input: [{ role: "user", content: fallback }],
      maxOutputTokens: 180,
      abortSignal,
    });
    const translated = clean(result.text, 700).replace(/^['"“”]+|['"“”]+$/g, "");
    if (!translated) throw openAIError(`Could not prepare the response in ${languageName}. Please try again.`, 502, "OPENAI_CUSTOMER_LANGUAGE_FAILED");
    return translated;
  } catch (error) {
    timer?.log("customer-localization-failed", { language, code: error?.code || null });
    throw error;
  }
}

async function understandRequest({ message, language, history, abortSignal, timer }) {
  const languageName = LANGUAGES[language] || LANGUAGES["en-NG"];
  const instructions = `You are Elevoni Assistant, the customer-facing agricultural marketplace assistant. Understand the customer's request and extract search, navigation, shopping-cart and buyer-demand intent in all five supported languages, including code-switching. If a buyer wants Elevoni to source a product or submit a specific buying requirement, use intent=demand; do not invent requirement fields. When a customer asks whether Elevoni has, sells, stocks or offers a named product, classify it as intent=search and extract the exact productName plus useful keywords, even if they do not say “find” or “buy”. Search both Elevoni Direct catalogue products and approved independent Marketplace listings before answering product-availability questions. The selected response language is ${languageName} (${language}); all user-facing text generated by the application must use that language. For Nigerian Pidgin, use natural Nigerian Pidgin. Preserve product names, locations, quantities and prices exactly. minPrice and maxPrice are per-unit price filters only when the user explicitly gives a per-unit budget; leave them null for an unclear total budget. Return structured criteria only. Do not invent missing details, listings, prices, stock, farmers, delivery coverage or business policies. Only classify; the server will verify products and apply cart changes. If a customer clearly wants a quantity of an Elevoni Direct catalogue product in any supported language (for example, “I want 5 kilos of smoked catfish”), use intent=cart, action=set_quantity, productName, quantity and unit. Normalize productName to the exact canonical catalogue name only when the product meaning is clear; never guess between similar products. Use add_quantity only for an explicitly additional quantity (“add another 2 kg”); subtract_quantity for reducing a quantity; remove_item for removing one product; clear_cart for emptying the cart; view_cart for viewing it; checkout for opening checkout. Do not add independent marketplace vendor listings to the cart: those are enquiry-only. If the product or quantity is unclear, do not guess. If the customer wants to submit a buying requirement or cannot find the product they need, set intent=demand. If the customer asks to navigate, set intent=navigate and destination only when clear. If unsure, use general. Categories: ${PRODUCT_CATEGORIES.join(" | ")}. Subcategories: ${JSON.stringify(SUBCATEGORIES_BY_CATEGORY)}. Conversation history is context, not a source of listing facts.`;
  const input = (Array.isArray(history) ? history : []).slice(-MAX_HISTORY).map((item) => ({
    role: item?.role === "assistant" ? "assistant" : "user", content: clean(item?.text, 700),
  })).filter((item) => item.content);
  input.push({ role: "user", content: clean(message, MAX_MESSAGE_LENGTH) });
  timer?.log("customer-openai-request-start");
  const result = await createOpenAIResponse({
    instructions,
    input,
    schema: customerCriteriaSchema,
    maxOutputTokens: 400,
    abortSignal,
  });
  timer?.log("customer-openai-request-end", { model: result.model });
  const criteria = normalizeCustomerCriteria(result.parsed || {}, message);
  const cartRequest = inferCustomerCartRequest(result.parsed || {}, message);
  return { ...criteria, ...cartRequest };
}

function serialiseListing({ product, stockMatch }, criteria) {
  const vendor = product.vendorId && typeof product.vendorId === "object" ? product.vendorId : {};
  const state = vendor.state || vendor.farmAddress?.state || product.originLocation?.state || "";
  const lga = vendor.lga || vendor.farmAddress?.lga || product.originLocation?.lga || "";
  return {
    id: String(product._id), name: clean(product.name, 120), description: clean(product.description, 260),
    category: clean(product.category, 80), subcategory: clean(product.subcategory, 80),
    price: Number(product.price), unit: clean(product.unitOfMeasure, 24),
    image: Array.isArray(product.images) ? product.images[0] || "" : "",
    vendorName: clean(vendor.businessName, 120), state, lga, stockMatch, source: "marketplace", sourceLabel: "Marketplace listing",
    matchReasons: [criteria.subcategory ? "Product type" : criteria.category ? "Product category" : "Product name", criteria.state && normalizeStateName(state) === normalizeStateName(criteria.state) ? "State" : "", criteria.lga && normalizeLgaName(lga) === normalizeLgaName(criteria.lga) ? "LGA" : "", stockMatch === "sufficient" ? "Recorded stock quantity" : ""].filter(Boolean),
    availability: product.availability || (product.isAvailable ? "Listed as available" : "Not available"),
  };
}

function routeForDestination(destination) {
  return ({ marketplace: "/marketplace", livestock: "/category/livestock", "food-crops": "/category/food-crops", "aquaculture-fishery": "/category/aquaculture-fishery", "smoked-catfish": "/#fish-display" })[destination] || "";
}

export async function answerCustomerElevoniAssistant({ message, language = "en-NG", history = [], cart = [], abortSignal, requestId }) {
  const timer = createTimer(requestId);
  timer.log("customer-request-start");
  const cleanMessage = clean(message, MAX_MESSAGE_LENGTH);
  if (!cleanMessage) {
    const error = new Error("Tell Elevoni Assistant what you are looking for."); error.status = 400; error.code = "ELEVONI_ASSISTANT_MESSAGE_EMPTY"; throw error;
  }
  if (!ELEVONI_LANGUAGES[language]) {
    const error = new Error("Choose one of Elevoni Assistant's supported languages."); error.status = 400; error.code = "ELEVONI_ASSISTANT_LANGUAGE_UNSUPPORTED"; throw error;
  }
  if (abortSignal?.aborted) {
    const error = new Error("Request cancelled."); error.status = 499; error.code = "NATLAS_CLIENT_ABORTED"; throw error;
  }
  const criteria = await understandRequest({ message: cleanMessage, language, history, abortSignal, timer });

  if (criteria.action === "view_cart") {
    return {
      reply: await localizeCustomerReply({ language, fallback: "You can review the items currently in your cart. Nothing has been ordered or paid for yet.", abortSignal, timer }),
      navigation: { label: await localizeCustomerReply({ language, fallback: "Go to cart", abortSignal, timer }), path: "/cart" },
      listings: [],
    };
  }
  if (criteria.action === "checkout") {
    return {
      reply: await localizeCustomerReply({ language, fallback: "Your next step is to review your cart and confirm delivery details at checkout. No payment has been made.", abortSignal, timer }),
      navigation: { label: await localizeCustomerReply({ language, fallback: "Review cart and checkout", abortSignal, timer }), path: "/order" },
      listings: [],
    };
  }
  if (criteria.action === "clear_cart") {
    const cartIds = (Array.isArray(cart) ? cart : []).filter((item) => /^[a-f0-9]{24}$/i.test(clean(item?.id, 32)) && Number(item?.quantity) > 0).map((item) => clean(item.id, 32));
    const verifiedCartProducts = cartIds.length ? await fishModel.find({ _id: { $in: cartIds }, vendorId: null, ...CATALOGUE_QUERY }).select("_id name").lean() : [];
    const cartActions = verifiedCartProducts.map((product) => ({ type: "set_quantity", productId: String(product._id), quantity: 0, productName: clean(product.name, 120) }));
    return {
      reply: await localizeCustomerReply({ language, fallback: cartActions.length ? "I've cleared the items from your cart. You can browse again whenever you're ready." : "Your cart is already empty.", abortSignal, timer }),
      cartActions,
      navigation: { label: await localizeCustomerReply({ language, fallback: "Go to cart", abortSignal, timer }), path: "/cart" },
      listings: [],
    };
  }
  if (["set_quantity", "add_quantity", "subtract_quantity", "remove_item"].includes(criteria.action)) {
    const catalogue = await fishModel.find({ ...CATALOGUE_QUERY, vendorId: null })
      .select("name description price image category pricingMode pricingTiers")
      .limit(100).lean();
    const match = matchDirectCatalogueProduct(catalogue, criteria.productName || criteria.keywords.join(" "));
    if (match.ambiguous) {
      return {
        reply: await localizeCustomerReply({ language, fallback: "I found more than one similar Elevoni Direct product. Please tell me the exact product name so I don't add the wrong item.", abortSignal, timer }),
        listings: [],
      };
    }
    if (match.product) {
      const productId = String(match.product._id);
      const current = (Array.isArray(cart) ? cart : []).find((item) => String(item?.id) === productId);
      const resolved = resolveCartQuantity({
        action: criteria.action,
        requestedQuantity: criteria.quantity,
        currentQuantity: current?.quantity || 0,
        unit: criteria.unit,
      });
      if (!resolved.ok) {
        const fallback = resolved.reason === "quantity"
          ? "How many whole kilograms would you like? The current smoked-catfish cart uses whole-kilogram quantities."
          : resolved.reason === "unit"
            ? "This Elevoni Direct product is sold by kilogram. How many whole kilograms would you like?"
            : "That product is not currently in your cart, so there is nothing to remove or reduce.";
        return { reply: await localizeCustomerReply({ language, fallback, abortSignal, timer }), listings: [] };
      }
      const productName = clean(match.product.name, 120);
      const cartActions = [{ type: "set_quantity", productId, quantity: resolved.quantity, productName }];
      const quantityText = `${resolved.quantity} kg`;
      const fallback = resolved.quantity > 0
        ? `I've updated ${productName} to ${quantityText} in your cart. Please review it before checkout; this is not an order or payment.`
        : `I've removed ${productName} from your cart. No order or payment has been made.`;
      return {
        reply: await localizeCustomerReply({ language, fallback, abortSignal, timer }),
        cartActions,
        navigation: { label: await localizeCustomerReply({ language, fallback: "Go to cart", abortSignal, timer }), path: "/cart" },
        listings: [],
      };
    }
    // If this is not an Elevoni Direct catalogue item, continue into marketplace
    // discovery only when we have real marketplace search criteria. Marketplace
    // listings are enquiry-only and are never carted.
    if (!criteria.category && !criteria.subcategory && !criteria.keywords.length) {
      return {
        reply: await localizeCustomerReply({ language, fallback: "I couldn't find that product in the Elevoni Direct checkout catalogue. You can explore independent Marketplace sellers instead, but their listings require an enquiry with the seller rather than adding them to this cart.", abortSignal, timer }),
        navigation: { label: await localizeCustomerReply({ language, fallback: "Explore marketplace", abortSignal, timer }), path: "/marketplace" },
        listings: [],
      };
    }
  }
  if (criteria.intent === "demand") {
    return {
      reply: await localizeCustomerReply({ language, fallback: "I can help you submit exactly what you need so Elevoni can look for suitable approved suppliers. Please complete the buying requirement form. Submitting it does not create an order or confirm stock.", abortSignal, timer }),
      navigation: { label: await localizeCustomerReply({ language, fallback: "Submit a buying requirement", abortSignal, timer }), path: "/marketplace#buyer-demand" },
      listings: [],
    };
  }
  if (criteria.intent === "navigate" && criteria.destination) {
    return {
      reply: await localizeCustomerReply({ language, fallback: "I can take you there. Tap the button below to open that part of Elevoni.", abortSignal, timer }),
      navigation: { label: await localizeCustomerReply({ language, fallback: `Open ${criteria.destination === "food-crops" ? "Food Crops" : criteria.destination === "aquaculture-fishery" ? "Aquaculture & Fishery" : criteria.destination === "smoked-catfish" ? "Smoked Catfish" : criteria.destination[0].toUpperCase() + criteria.destination.slice(1)}`, abortSignal, timer }), path: routeForDestination(criteria.destination) },
      listings: [],
    };
  }
  if (/\b(near me|nearby|closest|close to me)\b/i.test(cleanMessage) && !criteria.state && !criteria.lga) {
    return {
      reply: await localizeCustomerReply({ language, fallback: "Tell me your state or town so I can look for nearby listings. I do not assume your location.", abortSignal, timer }),
      navigation: { label: await localizeCustomerReply({ language, fallback: "Browse the marketplace", abortSignal, timer }), path: "/marketplace" }, listings: [],
    };
  }
  if (!criteria.category && !criteria.subcategory && !criteria.keywords.length && !criteria.productName) {
    return {
      reply: await localizeCustomerReply({ language, fallback: "I can help you find livestock, food crops, aquaculture and fishery products. Tell me the product, quantity and the state or town you prefer.", abortSignal, timer }),
      navigation: { label: await localizeCustomerReply({ language, fallback: "Browse the marketplace", abortSignal, timer }), path: "/marketplace" }, listings: [],
    };
  }

  const approvedProfiles = await vendorProfileModel.find({ status: "approved" }).select("_id state lga farmAddress").lean();
  const locationProfiles = approvedProfiles.filter((profile) => {
    const state = profile.state || profile.farmAddress?.state || "";
    const lga = profile.lga || profile.farmAddress?.lga || "";
    return (!criteria.state || normalizeStateName(state) === normalizeStateName(criteria.state))
      && (!criteria.lga || normalizeLgaName(lga) === normalizeLgaName(criteria.lga));
  });
  const approvedVendorIds = (criteria.state || criteria.lga ? locationProfiles : approvedProfiles).map((profile) => profile._id);
  const filter = buildListingFilter(criteria, approvedVendorIds);
  const found = approvedVendorIds.length ? await Product.find(filter)
    .select("name description category subcategory price unitOfMeasure images vendorId originLocation stockQuantity availability isAvailable updatedAt")
    .populate("vendorId", "businessName state lga farmAddress status")
    .sort({ updatedAt: -1 }).limit(40).lean() : [];
  const listings = rankCustomerListings(found, criteria).map((item) => serialiseListing(item, criteria));
  // Search Elevoni Direct alongside approved Marketplace listings. This ensures
  // Direct-only products are recognised even when no vendor has listed them.
  const directQuery = clean(criteria.productName || criteria.keywords.join(" "), 160);
  if (directQuery) {
    const directCatalogue = await fishModel.find({ ...CATALOGUE_QUERY, vendorId: null })
      .select("name description price image category pricingMode pricingTiers")
      .limit(100).lean();
    const directMatch = matchDirectCatalogueProduct(directCatalogue, directQuery);
    const directProducts = directMatch.ambiguous ? directMatch.candidates : directMatch.product ? [directMatch.product] : [];
    for (const fish of directProducts) {
      const firstTierPrice = Array.isArray(fish.pricingTiers) && fish.pricingTiers.length
        ? Number(fish.pricingTiers[0].unitPrice) : Number(fish.price);
      if (criteria.unit && criteria.unit !== "kg") continue;
      if (criteria.minPrice !== null && firstTierPrice < criteria.minPrice) continue;
      if (criteria.maxPrice !== null && firstTierPrice > criteria.maxPrice) continue;
      listings.push({
        id: String(fish._id), name: clean(fish.name, 120), description: clean(fish.description, 260),
        category: clean(fish.category || "Smoked Catfish", 80), subcategory: "Smoked Catfish",
        price: firstTierPrice, pricePrefix: fish.pricingMode === "tiered" ? "From" : "",
        unit: "kg", image: clean(fish.image, 500), vendorName: "Elevoni Farms",
        state: "", lga: "", stockMatch: "not_confirmed", matchReasons: ["Elevoni Direct catalogue"],
        availability: "Check current availability with Elevoni", houseProduct: true,
        source: "direct", sourceLabel: "Elevoni Direct",
      });
    }
  }
  if (!listings.length) {
    return {
      reply: await localizeCustomerReply({ language, fallback: ["set_quantity", "add_quantity", "subtract_quantity", "remove_item"].includes(criteria.action)
        ? "I couldn't find a matching product in Elevoni Direct or an approved Marketplace listing. No cart change was made. Try another product name or browse the marketplace."
        : criteria.state || criteria.lga
          ? "I could not find an approved listing matching those details in that location. Try another state or town, or browse all marketplace listings."
          : "I couldn't find an approved listing that matches those details right now. You can broaden the search by changing the product, location or budget. No supplier or stock has been assumed.", abortSignal, timer }),
      navigation: { label: await localizeCustomerReply({ language, fallback: "Browse all marketplace listings", abortSignal, timer }), path: "/marketplace" }, listings: [],
    };
  }
  const locationText = [criteria.lga, criteria.state].filter(Boolean).join(", ");
  const hasDirect = listings.some((item) => item.source === "direct");
  const hasMarketplace = listings.some((item) => item.source === "marketplace");
  const sourceSummary = hasDirect && hasMarketplace
    ? "I found this product in Elevoni Direct and also found approved Marketplace listings."
    : hasDirect
      ? "Yes — I found this product in Elevoni Direct. It is not showing among the matching approved Marketplace listings for this search."
      : "I found matching products in approved Marketplace listings.";
  const reply = await localizeCustomerReply({
    language,
    fallback: `${["set_quantity", "add_quantity", "subtract_quantity", "remove_item"].includes(criteria.action) ? "These Marketplace results are independent vendor listings and cannot currently be added to the Elevoni Direct checkout cart. You can enquire with those sellers instead. " : ""}${sourceSummary}${locationText ? ` Location filter: ${locationText}.` : ""} These results are not confirmed orders. Confirm current stock, final price and delivery before paying.`,
    abortSignal,
    timer,
  });
  timer.log("customer-request-end", { matchedListings: listings.length, intent: criteria.intent });
  return { reply, navigation: { label: await localizeCustomerReply({ language, fallback: hasDirect && !hasMarketplace ? "View Elevoni Direct product" : "See all marketplace listings", abortSignal, timer }), path: hasDirect && !hasMarketplace ? "/#fish-display" : "/marketplace" }, listings, criteria: { category: criteria.category, subcategory: criteria.subcategory, state: criteria.state, lga: criteria.lga, quantity: criteria.quantity, unit: criteria.unit } };
}
